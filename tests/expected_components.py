def capacitor(value, units, voltage, voltage_units, tolerance, case, variant):
    return (
        "C",
        value,
        units,
        voltage,
        voltage_units,
        tolerance,
        case,
        variant,
        "",
    )


def resistor(
    value,
    units,
    power=0.0,
    power_units="",
    tolerance=0,
    case="",
    manufacturer_part_number="",
):
    return (
        "R",
        value,
        units,
        power,
        power_units,
        tolerance,
        case,
        "-",
        manufacturer_part_number,
    )


def inductor(value, units, current, current_units, manufacturer_part_number):
    return (
        "L",
        value,
        units,
        current,
        current_units,
        0,
        "",
        "",
        manufacturer_part_number,
    )


